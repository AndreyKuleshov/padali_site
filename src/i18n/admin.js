function interpolate (template, params) {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, key) => (
    Object.hasOwn(params, key) ? String(params[key]) : match
  ))
}

/** Переводчик для одного языка: t('blocks.title') → строка. */
function adminTranslator (locale) {
  const strings = DICTIONARY[locale] ?? DICTIONARY[FALLBACK]
  return function t (key, params) {
    const template = strings[key] ?? DICTIONARY[FALLBACK][key] ?? key
    return interpolate(template, params)
  }
}

/** Языки, на которые переведён интерфейс админки. */
function translatedLocales () {
  return Object.keys(DICTIONARY)
}

/**
 * Подпись из дескриптора блока: `{ en, sr }` или просто строка.
 * Дескрипторы держат свои названия у себя — так добавление типа
 * остаётся одним файлом и не требует правок общего словаря.
 */
function localize (value, locale) {
  if (value == null) return ''
  if (typeof value === 'string') return value
  return value[locale] ?? value[FALLBACK] ?? Object.values(value)[0] ?? ''
}

export { adminTranslator, translatedLocales, localize, DICTIONARY, FALLBACK }
