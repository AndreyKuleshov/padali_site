-- Привязка клика к блоку страницы.
--
-- Раньше координаты писались от окна браузера: доля его ширины и
-- пиксели от верха документа. Но высота шапки задана в единицах
-- экрана, а колонка содержимого центрирована, поэтому у посетителя
-- с другим размером окна та же кнопка оказывалась в другом месте —
-- и карта кликов съезжала.
--
-- Теперь клик хранится относительно блока, в котором он случился:
-- доля ширины блока и пиксели от его верха. Старые записи остаются
-- с NULL и рисуются по-прежнему, от начала документа.
ALTER TABLE analytics_clicks ADD COLUMN anchor VARCHAR(64);
